#!/usr/bin/env node
// Generates src/lib/licences.generated.ts: name, version, licence and copyright line of every package the app is built
// from (what Metro packs into the iOS and Android release bundles, plus the direct dependencies), plus the native
// libraries the local module adds (Gradle). Run after changing dependencies: node scripts/gen-licences.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const rootPkg = readJson(join(root, 'package.json'));

function locate(name, fromDir) {
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const p = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(p)) return dirname(p);
    if (dir === dirname(dir) || dir.length < root.length) return null;
  }
}

// Which packages are in the app: every module in the release bundles' source maps (what Metro really packs for iOS and
// Android), plus the direct dependencies (their native code is linked even when no JS of theirs is imported).
const outDir = join(root, 'artifacts', 'licence-export');
execFileSync('npx', ['expo', 'export', '--platform', 'android', '--platform', 'ios', '--output-dir', outDir, '--source-maps'], {
  cwd: root,
  env: { ...process.env, APP_VARIANT: 'production' },
  stdio: 'ignore',
});
const names = new Set(Object.keys(rootPkg.dependencies));
for (const platform of ['android', 'ios']) {
  const dir = join(outDir, '_expo', 'static', 'js', platform);
  for (const f of readdirSync(dir).filter((x) => x.endsWith('.map'))) {
    for (const src of readJson(join(dir, f)).sources) {
      const i = src.lastIndexOf('node_modules/');
      if (i < 0) continue;
      const parts = src.slice(i + 13).split('/');
      names.add(parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0]);
    }
  }
}
const seen = new Map();
for (const name of names) {
  const dir = locate(name, root);
  if (!dir) continue;
  const pkg = readJson(join(dir, 'package.json'));
  seen.set(`${pkg.name}@${pkg.version}`, { dir, pkg });
}

function licenceOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === 'string') return l;
  if (l?.type) return l.type;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(' OR ');
  return 'UNKNOWN';
}

function copyrightOf(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  if (!file) return undefined;
  const line = readFileSync(join(dir, file), 'utf8').split('\n').find((l) => /^\s*(copyright|\(c\)|©)/i.test(l));
  return line?.trim().replace(/\s+/g, ' ').slice(0, 140);
}

const js = [...seen.values()]
  .map(({ dir, pkg }) => ({ name: pkg.name, version: pkg.version, licence: licenceOf(pkg), copyright: copyrightOf(dir) }))
  .sort((a, b) => a.name.localeCompare(b.name));

// Native libraries added by modules/safe-share-native (Gradle). React Native / Expo's own Gradle and Pod dependencies
// are part of those frameworks' packages above; Hermes and the AndroidX / Kotlin runtime come with React Native.
const native = [
  { name: 'metadata-extractor (com.drewnoakes)', version: '2.21.0', licence: 'Apache-2.0', copyright: 'Copyright Drew Noakes' },
  { name: 'XMP Core (com.adobe.xmp:xmpcore)', version: '6.1.11', licence: 'BSD-3-Clause', copyright: 'Copyright Adobe Systems Incorporated' },
  { name: 'Hermes JavaScript engine', version: 'with React Native 0.86', licence: 'MIT', copyright: 'Copyright Meta Platforms, Inc. and affiliates' },
  { name: 'AndroidX and Kotlin standard library', version: 'with React Native / Expo', licence: 'Apache-2.0', copyright: 'Copyright The Android Open Source Project, JetBrains s.r.o.' },
];

const out = `// GENERATED by scripts/gen-licences.mjs — do not edit. Regenerate after changing dependencies.
export interface LicenceEntry {
  name: string;
  version: string;
  licence: string;
  copyright?: string;
}

export const JS_LICENCES: LicenceEntry[] = ${JSON.stringify(js, null, 2)};

export const NATIVE_LICENCES: LicenceEntry[] = ${JSON.stringify(native, null, 2)};
`;
writeFileSync(join(root, 'src/lib/licences.generated.ts'), out);
console.log(`${js.length} packages, ${native.length} native libraries`);
const counts = {};
for (const e of js) counts[e.licence] = (counts[e.licence] ?? 0) + 1;
console.log(counts);
